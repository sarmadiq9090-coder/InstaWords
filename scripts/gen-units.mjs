// Embeds data/units.json into src/generated/units-data.ts so the core has no runtime file I/O.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const data = JSON.parse(readFileSync(root + "data/units.json", "utf8"));
delete data.$schema;
mkdirSync(root + "src/generated", { recursive: true });
writeFileSync(
  root + "src/generated/units-data.ts",
  `// GENERATED by scripts/gen-units.mjs from data/units.json — do not edit.\n` +
    `import type { UnitCatalog } from "../types.ts";\n\n` +
    `const data: UnitCatalog = ${JSON.stringify(data, null, 2)};\n\nexport default data;\n`,
);
console.log(`units-data.ts: ${data.units.length} units`);
