// Package manager manifests for a released version: winget (multi-file, from
// packaging/winget/templates/) and Scoop (packaging/scoop/instawords.json), plus SHA256SUMS.txt.
//
//   node scripts/package-manifests.mjs
//       From site/release-fallback.json (the published release): refreshes the committed copies,
//       packaging/winget/manifests/s/Sarmad/InstaWords/<version>/ and packaging/scoop/instawords.json.
//   node scripts/package-manifests.mjs --setup out/InstaWords_X_x64-setup.exe --portable out/InstaWords_X_x64-portable.zip \
//       [--version X] [--date YYYY-MM-DD] --out out/packages
//       From the built files (SHA-256 computed here), as the release job does. Writes
//       <out>/winget-manifests/manifests/s/Sarmad/InstaWords/<version>/*.yaml, <out>/instawords.json
//       and <out>/SHA256SUMS.txt.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";
import { ROOT, VERSION_RE, assetUrl, portableName, readFallback, setupName } from "./lib/release.mjs";

export const PACKAGE_IDENTIFIER = "Sarmad.InstaWords";
// winget-pkgs layout: manifests/<first letter, lower case>/<Publisher>/<Name>/<version>/
export const WINGET_DIR = ["manifests", "s", "Sarmad", "InstaWords"];
const TEMPLATES = join(ROOT, "packaging", "winget", "templates");
const SCOOP = join(ROOT, "packaging", "scoop", "instawords.json");

const args = process.argv.slice(2);
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const fail = (msg) => {
  console.error(`package-manifests: ${msg}`);
  process.exit(1);
};
const sha256 = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");

function release() {
  const setupFile = option("--setup");
  const portableFile = option("--portable");
  if (!setupFile && !portableFile) {
    const fb = readFallback();
    return { version: fb.version, date: fb.date.slice(0, 10), setup: fb.setup, portable: fb.portable, fromFiles: false };
  }
  if (!setupFile || !portableFile) fail("--setup and --portable go together");
  for (const f of [setupFile, portableFile]) if (!existsSync(f) || !statSync(f).isFile()) fail(`${f} not found`);
  const version = option("--version") ?? /^InstaWords_([\d.]+(?:-[0-9A-Za-z.-]+)?)_x64-setup\.exe$/.exec(basename(setupFile))?.[1];
  if (!VERSION_RE.test(version ?? "")) fail(`cannot tell the version (pass --version x.y.z): ${version}`);
  for (const [f, name] of [[setupFile, setupName(version)], [portableFile, portableName(version)]]) {
    if (basename(f) !== name) fail(`${f} must be named ${name} (the updater and the manifests rely on it)`);
  }
  const date = option("--date") ?? new Date().toISOString().slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) fail(`--date must be YYYY-MM-DD: ${date}`);
  const file = (f) => ({ name: basename(f), url: assetUrl(version, basename(f)), size: statSync(f).size, sha256: sha256(f) });
  return { version, date, setup: file(setupFile), portable: file(portableFile), fromFiles: true };
}

function winget(r) {
  const values = { VERSION: r.version, RELEASE_DATE: r.date, SETUP_URL: r.setup.url, SETUP_SHA256: r.setup.sha256.toUpperCase() };
  const files = {};
  for (const name of readdirSync(TEMPLATES).filter((n) => n.endsWith(".yaml")).sort()) {
    let text = readFileSync(join(TEMPLATES, name), "utf8").replace(/^# Template:.*$/m, "# Generated by scripts/package-manifests.mjs from packaging/winget/templates/");
    text = text.replace(/\$\{([A-Z_0-9]+)\}/g, (m, key) => {
      if (!(key in values)) fail(`${name}: unknown placeholder ${m}`);
      return values[key];
    });
    if (!text.startsWith("# Generated") || !text.includes(`PackageIdentifier: ${PACKAGE_IDENTIFIER}\n`)) fail(`${name}: unexpected template header`);
    files[name] = text;
  }
  const expected = ["", ".installer", ".locale.en-US", ".locale.ar-SA"].map((s) => `${PACKAGE_IDENTIFIER}${s}.yaml`).sort();
  if (JSON.stringify(Object.keys(files).sort()) !== JSON.stringify(expected)) fail(`templates must be exactly ${expected.join(", ")}`);
  return files;
}

function scoop(r) {
  const m = JSON.parse(readFileSync(SCOOP, "utf8"));
  if (!r.portable) fail("the release has no portable zip, which the Scoop manifest installs");
  m.version = r.version;
  m.url = r.portable.url;
  m.hash = r.portable.sha256.toLowerCase();
  return `${JSON.stringify(m, null, 4)}\n`;
}

function write(path, text) {
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, text);
  console.log(`  ${relative(process.cwd(), path)}`);
}

const r = release();
const yamls = winget(r);
const scoopJson = scoop(r);
const outDir = option("--out");
console.log(`package-manifests: ${PACKAGE_IDENTIFIER} ${r.version} (${r.date}) setup ${r.setup.sha256} portable ${r.portable.sha256}`);

if (outDir) {
  const wingetDir = join(outDir, "winget-manifests", ...WINGET_DIR, r.version);
  rmSync(join(outDir, "winget-manifests"), { recursive: true, force: true });
  for (const [name, text] of Object.entries(yamls)) write(join(wingetDir, name), text);
  write(join(outDir, "instawords.json"), scoopJson);
  write(join(outDir, "SHA256SUMS.txt"), `${r.setup.sha256}  ${r.setup.name}\n${r.portable.sha256}  ${r.portable.name}\n`);
} else {
  if (r.fromFiles) fail("--out is required with --setup/--portable (the committed copies follow site/release-fallback.json)");
  const base = join(ROOT, "packaging", "winget", ...WINGET_DIR);
  // Keep only the current version, like the InstaFind repository.
  if (existsSync(base)) for (const v of readdirSync(base)) if (v !== r.version) rmSync(join(base, v), { recursive: true, force: true });
  for (const [name, text] of Object.entries(yamls)) write(join(base, r.version, name), text);
  write(SCOOP, scoopJson);
}
