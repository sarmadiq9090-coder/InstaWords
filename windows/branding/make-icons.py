#!/usr/bin/env python3
"""
Makes the InstaWords Windows app icon from windows/branding/instawords.svg (see brandicon.py):

  windows/InstaWords.App/Assets/InstaWords.ico   exe, window title bars, tray, installer (SetupIconFile)
      16, 20, 24, 32, 40, 48, 64, 256 px, the plated icon (the green tile); BMP frames below 256,
      PNG at 256.
  windows/InstaWords.App/Themes/Brand.xaml       LogoImage, the same SVG as a WPF vector drawing
      (main window header, About, update window), between the "generated" comments.

The outputs are committed; run this again only when the icon changes:

    pip install Pillow          # any recent version
    python3 windows/branding/make-icons.py

The Store package assets come from the same SVG: windows/packaging/msix/make-assets.py.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.dont_write_bytecode = True  # no __pycache__ in the repo
import brandicon as b  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(b.HERE))  # repo root
APP = os.path.join(ROOT, "windows", "InstaWords.App")
ICO = os.path.join(APP, "Assets", "InstaWords.ico")
BRAND_XAML = os.path.join(APP, "Themes", "Brand.xaml")
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 256)

BEGIN = "<!-- BEGIN generated by windows/branding/make-icons.py: do not edit by hand. -->"
END = "<!-- END generated by windows/branding/make-icons.py -->"
CAPS = {"round": "Round", "butt": "Flat", "square": "Square"}
JOINS = {"round": "Round", "miter": "Miter", "bevel": "Bevel"}


def color(v):
    return "#" + v[1:].upper()


def brush(fill, grads, indent):
    """(Brush attribute, child elements) for an SVG fill."""
    m = re.fullmatch(r"url\(#(.+)\)", fill)
    if not m:
        return f' Brush="{color(fill)}"', []
    (x1, y1, x2, y2), stops = grads[m.group(1)]
    pad = " " * indent
    lines = [f"{pad}<GeometryDrawing.Brush>",
             f'{pad}  <LinearGradientBrush StartPoint="{b.f(x1)},{b.f(y1)}" EndPoint="{b.f(x2)},{b.f(y2)}">']
    lines += [f'{pad}    <GradientStop Offset="{b.f(o)}" Color="{color(c)}" />' for o, c in stops]
    lines += [f"{pad}  </LinearGradientBrush>", f"{pad}</GeometryDrawing.Brush>"]
    return "", lines


def xaml_drawing(path=b.MASTER):
    """The SVG as WPF drawing elements, element for element (the drawing is the master itself)."""
    root = ET.parse(path).getroot()
    _, grads, _ = b.load(path)

    def walk(el, indent):
        pad = " " * indent
        out = []
        for ch in el:
            tag = ch.tag[len(b.NS):]
            if tag == "defs":
                continue
            if tag == "g":
                a, cx, cy = b._transform(ch.get("transform"))
                out += [f"{pad}<DrawingGroup>", f"{pad}  <DrawingGroup.Transform>",
                        f'{pad}    <RotateTransform Angle="{b.f(a)}" CenterX="{b.f(cx)}" CenterY="{b.f(cy)}" />',
                        f"{pad}  </DrawingGroup.Transform>"]
                out += walk(ch, indent + 2)
                out.append(f"{pad}</DrawingGroup>")
                continue
            if tag == "rect":
                r = ch.get("rx", "0")
                geo = (f'<RectangleGeometry Rect="{ch.get("x", "0")},{ch.get("y", "0")},{ch.get("width")},'
                       f'{ch.get("height")}" RadiusX="{r}" RadiusY="{r}" />')
            elif tag == "circle":
                geo = (f'<EllipseGeometry Center="{ch.get("cx")},{ch.get("cy")}" RadiusX="{ch.get("r")}" '
                       f'RadiusY="{ch.get("r")}" />')
            elif tag == "path":
                geo = None
            else:
                raise ValueError(f"unsupported SVG element <{tag}>")
            fill = ch.get("fill", "#000000")
            stroke = ch.get("stroke", "none")
            if fill == "none" or (tag == "path" and all(len(p) < 3 for p, _ in b.flatten(ch.get("d")))):
                attr, kids = "", []
            else:
                attr, kids = brush(fill if fill.startswith("url(") else fill.lower(), grads, indent + 2)
            if stroke != "none":
                cap = CAPS[ch.get("stroke-linecap", "butt")]
                kids += [f"{pad}  <GeometryDrawing.Pen>",
                         f'{pad}    <Pen Brush="{color(stroke.lower())}" Thickness="{ch.get("stroke-width", "1")}" '
                         f'StartLineCap="{cap}" EndLineCap="{cap}" '
                         f'LineJoin="{JOINS[ch.get("stroke-linejoin", "miter")]}" />',
                         f"{pad}  </GeometryDrawing.Pen>"]
            if geo is None:  # path data: F1 = nonzero, SVG's default fill rule
                attr += f' Geometry="F1 {ch.get("d")}"'
            if not kids and geo is None:
                out.append(f"{pad}<GeometryDrawing{attr} />")
                continue
            out.append(f"{pad}<GeometryDrawing{attr}>")
            out += kids
            if geo is not None:
                out += [f"{pad}  <GeometryDrawing.Geometry>", f"{pad}    {geo}", f"{pad}  </GeometryDrawing.Geometry>"]
            out.append(f"{pad}</GeometryDrawing>")
        return out

    return walk(root, 8)


def write_xaml():
    with open(BRAND_XAML, encoding="utf-8") as fh:
        text = fh.read()
    block = "\n".join([
        "  " + BEGIN,
        "  <!-- The InstaWords icon (windows/branding/instawords.svg, the pen nib writing a stroke) as a vector",
        "       drawing, crisp at any DPI: main window header 34 px, About 64, update window 52. -->",
        '  <DrawingImage x:Key="LogoImage">',
        "    <DrawingImage.Drawing>",
        "      <DrawingGroup>",
        *xaml_drawing(),
        "      </DrawingGroup>",
        "    </DrawingImage.Drawing>",
        "  </DrawingImage>",
        "  " + END,
    ])
    pattern = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        sys.exit(f"{os.path.relpath(BRAND_XAML, ROOT)}: generated-block markers not found")
    new = pattern.sub(lambda m: block, text)
    with open(BRAND_XAML, "w", encoding="utf-8", newline="") as fh:
        fh.write(new)


def main():
    data = b.ico_bytes([b.render(s) for s in ICO_SIZES])
    with open(ICO, "wb") as fh:
        fh.write(data)
    print(f"{os.path.relpath(ICO, ROOT)}: {len(ICO_SIZES)} sizes, {len(data)} bytes")
    write_xaml()
    print(f"{os.path.relpath(BRAND_XAML, ROOT)}: LogoImage")
    return 0


if __name__ == "__main__":
    sys.exit(main())
