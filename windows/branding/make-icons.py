#!/usr/bin/env python3
"""
Makes the InstaWords Windows app icon from the brand v2 SVGs in this folder (see brandicon.py):

  windows/InstaWords.App/Assets/InstaWords.ico   exe, window title bars, tray, installer (SetupIconFile)
      16, 20, 24, 32, 40, 48, 64, 256 px; 16-40 from the hand-tuned small drawings, 48 up from the
      full tile with the seed; BMP frames below 256, PNG at 256.
  windows/InstaWords.App/Themes/Brand.xaml       the LogoImage / LogoImageSmall vector drawings
      (About, update window, main window header), between the "generated" comments.

The outputs are committed; run this again only when the brand files change:

    pip install Pillow          # any recent version
    python3 windows/branding/make-icons.py

The Store package assets come from the same SVGs: windows/packaging/msix/make-assets.py.
"""
import os
import re
import sys

sys.dont_write_bytecode = True  # no __pycache__ in the repo
import brandicon as b  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(b.HERE))  # repo root
APP = os.path.join(ROOT, "windows", "InstaWords.App")
ICO = os.path.join(APP, "Assets", "InstaWords.ico")
BRAND_XAML = os.path.join(APP, "Themes", "Brand.xaml")
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 256)

BEGIN = "<!-- BEGIN generated by windows/branding/make-icons.py: do not edit by hand. -->"
END = "<!-- END generated by windows/branding/make-icons.py -->"


def drawing_image(key, grid, edge, note):
    """A WPF DrawingImage of the plated icon on a grid x grid canvas (edge in grid units)."""
    glyph, seed = b.drawing(grid)
    lines = [f"  <!-- {note} -->", f'  <DrawingImage x:Key="{key}">', "    <DrawingImage.Drawing>",
             "      <DrawingGroup>"]
    for fill, evenodd, d in b.tile(grid, edge) + glyph + seed:
        # WPF path markup: F0 = evenodd, F1 = nonzero (SVG's default)
        lines.append(f'        <GeometryDrawing Brush="{fill}" Geometry="{"F0" if evenodd else "F1"} {d}" />')
    lines += ["      </DrawingGroup>", "    </DrawingImage.Drawing>", "  </DrawingImage>"]
    return "\n".join(lines)


def write_xaml():
    with open(BRAND_XAML, encoding="utf-8") as fh:
        text = fh.read()
    block = "\n".join([
        "  " + BEGIN,
        drawing_image("LogoImage", 256, 4.0,
                      "The InstaWords icon (brand v2, windows/branding/instawords.svg), for 41 px and up "
                      "(About 64, update window 52). Tile edge 4/256: 1 px at 64."),
        drawing_image("LogoImageSmall", 32, 1.0,
                      "The hand-tuned 32 px drawing (instawords-32.svg, no seed), for 28-40 px "
                      "(the main window header, 34)."),
        "  " + END,
    ])
    pattern = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        sys.exit(f"{os.path.relpath(BRAND_XAML, ROOT)}: generated-block markers not found")
    new = pattern.sub(lambda m: block, text)
    with open(BRAND_XAML, "w", encoding="utf-8", newline="") as fh:
        fh.write(new)


def main():
    data = b.ico_bytes([b.icon(s) for s in ICO_SIZES])
    with open(ICO, "wb") as fh:
        fh.write(data)
    print(f"{os.path.relpath(ICO, ROOT)}: {len(ICO_SIZES)} sizes, {len(data)} bytes")
    write_xaml()
    print(f"{os.path.relpath(BRAND_XAML, ROOT)}: LogoImage, LogoImageSmall")
    return 0


if __name__ == "__main__":
    sys.exit(main())
